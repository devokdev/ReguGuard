"""
ReguGuard Provenance Graph & Audit Pack Generator
=================================================
Builds complete verifiable audit provenance linking:
Claim -> Verified Quote -> Source Gazette Document -> Section & Date -> Producing Agent -> Span ID.

Single Source of Truth: PRD §8.3, §14 Step 12 (Criterion 9)
"""

from __future__ import annotations
import json
from pathlib import Path
from typing import Dict, List, Any
from src.schemas import ImpactReport
from src.observability.trace_store import trace_store


class ProvenancePackGenerator:
    """Generates verifiable JSON and Markdown audit packs for auditors and consultants."""

    def __init__(self, report: ImpactReport):
        self.report = report

    def generate_provenance_graph(self) -> Dict[str, Any]:
        """Constructs an auditable DAG connecting final verdict to source text and trace spans."""
        spans = trace_store.get_trace_events(self.report.trace_id)
        span_map = {s.agent: s.span_id for s in spans}

        evidence_nodes = []
        for ev in self.report.evidence:
            evidence_nodes.append({
                "claim": ev.claim,
                "quote": ev.quote,
                "source_doc_id": ev.source_doc_id,
                "section": ev.section,
                "verified": ev.verified,
                "producing_agent": "EvidenceVerificationCrew",
                "span_id": span_map.get("EvidenceVerificationCrew", "span-crewai")
            })

        graph = {
            "case_id": self.report.case_id,
            "trace_id": self.report.trace_id,
            "sme_id": self.report.sme_id,
            "verdict": self.report.verdict.verdict,
            "confidence": self.report.verdict.confidence,
            "headline": self.report.headline,
            "evidence_chain": evidence_nodes,
            "action_plan": self.report.action.model_dump() if self.report.action else None,
            "total_latency_s": self.report.metrics.total_latency_s,
            "total_tokens": self.report.metrics.total_tokens
        }
        return graph

    def export_audit_pack(self, output_dir: Path | str = "data/eval/audit_packs") -> Dict[str, str]:
        """Writes audit pack as JSON and formatted Markdown."""
        out_path = Path(output_dir)
        out_path.mkdir(parents=True, exist_ok=True)

        graph = self.generate_provenance_graph()

        # 1. JSON Audit Pack
        json_file = out_path / f"{self.report.case_id}_audit.json"
        json_file.write_text(json.dumps(graph, indent=2, default=str), encoding="utf-8")

        # 2. Markdown Audit Report
        md_file = out_path / f"{self.report.case_id}_audit.md"
        md_content = f"""# ReguGuard Audit Pack — Provenance & Verification Log
**Case ID:** {self.report.case_id}  
**Trace ID:** `{self.report.trace_id}`  
**Subject SME:** {self.report.sme_id}  
**Mandatory Headline:** {self.report.headline}  

---

## 1. Regulatory Impact Verdict
- **Verdict:** `{self.report.verdict.verdict.upper()}`
- **Assessed Confidence:** {self.report.verdict.confidence * 100:.1f}%
- **Summary:** {self.report.verdict.reasoning_summary}

## 2. Grounded Evidence Chain (Substring Verified)
| Section | Source Doc | Quote | Verification Status | Producing Agent |
|---|---|---|---|---|
"""
        for ev in graph["evidence_chain"]:
            status_emoji = "✅ Pass" if ev["verified"] else "❌ Fail"
            md_content += f"| {ev['section']} | {ev['source_doc_id']} | \"{ev['quote']}\" | {status_emoji} | {ev['producing_agent']} |\n"

        md_content += f"""
---
*Generated by ReguGuard Autonomous Audit Engine · CSE3101 Agentic AI*
"""
        md_file.write_text(md_content, encoding="utf-8")

        return {
            "json_path": str(json_file),
            "markdown_path": str(md_file)
        }
